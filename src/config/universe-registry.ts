import {TemporalEpoch, Universe, UniverseNetwork} from '../core/types';
import { UniverseId, isValidUniverseId, createUniverseId } from '../core/universe-ids';
import { CommonUniverseIds } from '../core/common-universe-ids';
import { ConfigLoader } from './config-loader';

/** A missing optional module: Node's ESM error code, or a CJS `require`'s. */
function isModuleNotFound(error: unknown): boolean {
  const code = (error as { code?: string } | undefined)?.code;
  return code === 'ERR_MODULE_NOT_FOUND' || code === 'MODULE_NOT_FOUND';
}

/**
 * The `UniverseBuilder.addConnection` `type` values that mean *containment* —
 * the source is a member of the target. A builder authors containment this way
 * (it lands in `metadata.connections`); a hand-authored literal authors it as
 * the top-level `connections.natural.parentUniverses`. Both are the same edge
 * (james-gibson/local-time#74), so both are read.
 */
const CONTAINMENT_CONNECTION_TYPES = new Set<string>(['member_of']);

/** `value` as an array: an array is itself, anything else is `[]`. */
function asArray(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}

/**
 * The universes generated by the lore pipeline (`scripts/sync-lore.sh`), if its
 * tree is present (james-gibson/local-time#98).
 *
 * The generated modules live under the git-ignored `src/config/universes/imported/`
 * — they carry a **private** KB's lore and this repo is public, so they are never
 * committed. Nothing can therefore *statically* import them: a clean checkout has no
 * such directory, and `tsc` would fail on the missing module. So the specifier below
 * is built at runtime on purpose (`tsc` never resolves it) and resolved relative to
 * this module. When the tree is absent the import rejects with a module-not-found
 * error and we return nothing — the clean-checkout case is not an error.
 */
export async function loadGeneratedUniverses(): Promise<Universe[]> {
  try {
    const specifier: string = './universes/imported/' + 'index.js';
    const mod = (await import(specifier)) as { importedUniverses?: unknown };
    return Array.isArray(mod.importedUniverses) ? (mod.importedUniverses as Universe[]) : [];
  } catch (error) {
    if (!isModuleNotFound(error)) {
      console.warn('Generated lore universes could not be loaded:', error);
    }
    return [];
  }
}

export class UniverseRegistry {
  private universes = new Map<UniverseId, Universe>();
  private aliases = new Map<string, UniverseId>();
  private networks = new Map<string, UniverseNetwork>();
  
  constructor(private configLoader: ConfigLoader) {}
  
  async initialize(): Promise<void> {
    await this.loadBuiltInUniverses();
    await this.registerGeneratedUniverses();
    await this.loadExternalConfig();
  }
  
  registerUniverse(id: string, universe: Universe): void {
    if (!id && !!universe['universeId']) { id = universe['universeId']; }
    if (!id) { return;}
    // Validate and convert to branded UniverseId
    if (!isValidUniverseId(id)) {
      throw new Error(`Invalid universe ID format: ${id}. Must follow pattern like 'category:identifier:year'`);
    }
    
    const universeId = createUniverseId(id);
    
    // Ensure universe object uses the same ID
    if (universe.universeId !== universeId) {
      universe.universeId = universeId;
    }

      const epochs = {
        "unix": {
          "epochId": "utc:unix_epoch",
          "startTime": "0",
          "endTime": "2147483647000000000",
          "precision": "NANOSECOND",
          "description": "Unix epoch (January 1, 1970, 00:00:00 UTC to January 19, 2038, 03:14:07 UTC)",
          "zeroPoint": "0", // + Math.random().toString(36),
          "zeroEvent": "Unix epoch start",
          "beforePrefix": "BCE-",
          "afterPrefix": "CE+",
          "relativeFormat": "TIMESTAMP"
        } as unknown as TemporalEpoch,

        "gregorian": {
          "epochId": "utc:gregorian",
          "startTime": "-62135596800000000000",
          "endTime": "253402300799000000000",
          "precision": "DAY",
          "description": "Gregorian calendar system (January 1, 0001 to December 31, 9999)",
          "zeroPoint": "-62135596800000000000",
          "zeroEvent": "Anno Domini start",
          "beforePrefix": "BCE ",
          "afterPrefix": "CE ",
          "relativeFormat": "CALENDAR"
        } as unknown as TemporalEpoch,
        // "modern": {
        //   "epochId": "utc:atomic_time",
        //   "startTime": "-315619200000000000",
        //   "endTime": "1722441600000000000",
        //   "precision": "SECOND",
        //   "description": "International Atomic Time coordination (January 1, 1960 to present)",
        //   "zeroPoint": "-315619200000000000",
        //   "zeroEvent": "TAI established",
        //   "beforePrefix": "Pre-TAI-",
        //   "afterPrefix": "TAI+",
        //   "relativeFormat": "SECONDS"
        // } as unknown as TemporalEpoch,
        // "y2k": {
        //   "epochId": "utc:millennium",
        //   "startTime": "946684800000000000",
        //   "endTime": "32503680000000000000",
        //   "precision": "MILLISECOND",
        //   "description": "21st century epoch (January 1, 2000, 00:00:00 UTC to December 31, 2999, 23:59:59 UTC)",
        //   "zeroPoint": "946684800000000000",
        //   "zeroEvent": "Y2K millennium start",
        //   "beforePrefix": "Y2K-",
        //   "afterPrefix": "Y2K+",
        //   "relativeFormat": "ISO8601"
        // } as unknown as TemporalEpoch,
        // "javascript": {
        //   "epochId": "utc:ecmascript",
        //   "startTime": "0",
        //   "endTime": "8640000000000000",
        //   "precision": "MILLISECOND",
        //   "description": "JavaScript Date range (±100,000,000 days from Unix epoch)",
        //   "zeroPoint": "0",
        //   "zeroEvent": "ECMAScript epoch",
        //   "beforePrefix": "JS-",
        //   "afterPrefix": "JS+",
        //   "relativeFormat": "MILLISECONDS"
        // } as unknown as TemporalEpoch,
      }
      if (!universe.epochs) universe.epochs = {};
    universe.epochs = { ...universe.epochs, ...epochs};

    if (universe.layers) {
      for (const layer of universe.layers) {
        // console.dir(layer)
        for (const e in layer.epochs) {
          const epoch = layer.epochs[e];
          // The layer key is the epoch's id. Some universes omit `epochId` on
          // the epoch object itself; fall back to the layer key rather than
          // silently dropping the whole universe (james-gibson/local-time#19).
          const epochId = epoch.epochId ?? e;
          if (!epoch.epochId) {
            console.warn(
              `UniverseRegistry: epoch "${e}" of universe "${id}" is missing an epochId; using its layer key.`
            );
            epoch.epochId = epochId;
          }
          universe.epochs[epochId] = epoch;
        }

      }
    }

    // console.trace(universe.epochs);
    if (!this.universes.has(universeId)) {
      this.universes.set(universeId, universe);
    }

    this.registerDeclaredContainment(universeId, universe);

    if (universe.identifiers?.aliases) {
      for (const alias of universe.identifiers.aliases) {
        this.aliases.set(alias, universeId);
      }
    }
  }

  /**
   * Make the containment convention real: a universe that declares a parent
   * becomes a member of it in `CommonUniverseIds`, so `contains()` /
   * `getChildren()` / `getAllDescendants()` see it.
   *
   * Until james-gibson/local-time#106 the registry was closed — the declared
   * convention ~20 universes already used was read by nobody, so declaring a
   * parent did not make a universe a descendant of it. The registry is the right
   * place to derive the edges: it is the one code path every universe passes
   * through, and `src/core` cannot see `src/config` (where the universes live).
   *
   * A universe has exactly one *owner* — its `universeId` — and any number of
   * *memberships*; this is the memberships half (james-gibson/local-time#74).
   */
  private registerDeclaredContainment(id: UniverseId, universe: Universe): void {
    const parents = this.declaredParentUniverses(universe);
    if (parents.length > 0) {
      CommonUniverseIds.registerUniverseLinks(id, parents);
    }
  }

  /**
   * Every container `universe` declares membership of, from either author path:
   *
   * - the first-class `connections.natural.parentUniverses` (hand-authored
   *   literals), and
   * - `metadata.connections` entries of a containment type
   *   (`{ type: 'member_of', targetUniverseId }`), which is what
   *   `UniverseBuilder.addConnection` writes.
   *
   * A declared parent may be written either as a real id or as the symbolic name
   * the KB's `parent-universes` frontmatter uses (`SOFTWARE_ENGINEERING`); both are
   * resolved through `CommonUniverseIds.resolveDeclaredName`. An entry that
   * resolves to nothing is reported and dropped — never dropped in silence, which
   * is how 24 declared edges went missing unnoticed (james-gibson/local-time#133).
   * Duplicates collapse.
   */
  private declaredParentUniverses(universe: Universe): UniverseId[] {
    const declared: unknown[] = [];

    const connections = universe.connections;
    if (connections && typeof connections === 'object' && !Array.isArray(connections)) {
      declared.push(...asArray(connections.natural?.parentUniverses));
    }

    const metadataConnections = (universe.metadata as { connections?: unknown } | undefined)?.connections;
    for (const entry of asArray(metadataConnections)) {
      const connection = entry as { type?: unknown; targetUniverseId?: unknown } | null;
      if (typeof connection?.type === 'string' && CONTAINMENT_CONNECTION_TYPES.has(connection.type)) {
        declared.push(connection.targetUniverseId);
      }
    }

    const resolved: UniverseId[] = [];
    for (const parent of declared) {
      if (typeof parent !== 'string' || parent.trim() === '') continue;

      const id = CommonUniverseIds.resolveDeclaredName(parent);
      if (id) {
        resolved.push(id);
        continue;
      }

      // Loud, not silent. A declared parent that is neither a universe id nor a
      // known container name is a KB or pipeline defect — the edge is dropped
      // either way, but the drop is now visible.
      console.warn(
        `UniverseRegistry: universe "${universe.universeId}" declares parent "${parent}", ` +
          'which is neither a universe id nor a known container name; the edge is dropped.',
      );
    }
    return [...new Set(resolved)];
  }
  
  getUniverse(idOrAlias: string): Universe | undefined {
    // Try as direct universe ID first
    if (isValidUniverseId(idOrAlias)) {
      const universeId = createUniverseId(idOrAlias);
      const universe = this.universes.get(universeId);
      if (universe) return universe;
    }
    
    // Try as alias
    const universeId = this.aliases.get(idOrAlias);
    if (universeId) {
      return this.universes.get(universeId);
    }
    
    return undefined;
  }
  
  /**
   * Register a network and index its members.
   *
   * Never throws. A network is a grouping, not a universe, and a problem with one member
   * must not cost the caller the network itself.
   *
   * #57: the previous version registered the network *as a universe* under its own
   * `networkId`:
   *
   *     this.registerUniverse(network.networkId, network as unknown as Universe);
   *
   * `registerUniverse` throws for an id that is not a valid universe id, and a network id
   * never is — `nasa` is not `category:identifier:year`. Because this method was `async` and
   * its callers did not await it, the throw escaped as an unhandled rejection and
   * `this.networks.set(...)` below never ran. So **a network with any members could never
   * be registered at all.** `disney` and `marvel` appeared to work only because their
   * member sets are empty, which is also why this went unnoticed for so long.
   *
   * Ordering is the fix: the network is stored first, so nothing after this point can
   * prevent it from being registered.
   *
   * The alias is set only when the network has no existing alias, so a multi-member network
   * resolves to its first member deterministically rather than whichever member happened to
   * be iterated last.
   */
  async registerNetwork(network: UniverseNetwork): Promise<void> {
    if (!network?.networkId) return;
    this.networks.set(network.networkId, network);

    for (const memberId of network.universes ?? []) {
      try {
        if (!this.getUniverse(memberId) && isValidUniverseId(memberId)) {
          if (!this.aliases.has(network.networkId)) {
            this.aliases.set(network.networkId, createUniverseId(memberId));
          }
        }
      } catch (error) {
        console.warn(`Network "${network.networkId}" member "${memberId}" not indexed:`, error);
      }
    }
  }
  
  getNetwork(networkId: string): UniverseNetwork | undefined {
    return this.networks.get(networkId);
  }
  
  getAllUniverses(): Universe[] {
    return Array.from(this.universes.values());
  }

  // === CONTAINMENT: one owner, many memberships (james-gibson/local-time#74) ===
  //
  // A universe is *owned* by exactly one `universeId`; the same universe may be
  // a *member* of any number of containers, declared through either the
  // top-level `connections.natural.parentUniverses` or a builder's
  // `addConnection({ type: 'member_of', ... })`. Both are folded into
  // `CommonUniverseIds` by `registerDeclaredContainment`, and these methods are
  // the read surface over that — so a collection can answer membership without
  // a universe ever being registered twice.

  /**
   * The universe that **owns** `id` — the record registered under it. One id has
   * exactly one owner; a later registration of the same id is ignored (first
   * registration wins), never merged. See {@link getMemberships} for the
   * many-to-many half.
   */
  getOwner(id: string): Universe | undefined {
    return this.getUniverse(id);
  }

  /** Every container `id` is a **direct** member of. */
  getMemberships(id: string): UniverseId[] {
    if (!isValidUniverseId(id)) return [];
    return CommonUniverseIds.getParents(createUniverseId(id));
  }

  /** Every container `id` is a member of, transitively. */
  getParentChain(id: string): UniverseId[] {
    if (!isValidUniverseId(id)) return [];
    return CommonUniverseIds.getParentChain(createUniverseId(id));
  }

  /** The ids **directly** contained by `container`. */
  getChildren(container: string): UniverseId[] {
    if (!isValidUniverseId(container)) return [];
    return [...CommonUniverseIds.getChildren(createUniverseId(container))];
  }

  /** Every id contained by `container`, transitively. */
  getDescendants(container: string): UniverseId[] {
    if (!isValidUniverseId(container)) return [];
    return [...CommonUniverseIds.getAllDescendants(createUniverseId(container))];
  }

  /** Is `contained` a member of `container`, directly or transitively? */
  contains(container: string, contained: string): boolean {
    if (!isValidUniverseId(container) || !isValidUniverseId(contained)) return false;
    return CommonUniverseIds.contains(createUniverseId(container), createUniverseId(contained));
  }

  private async loadBuiltInUniverses(): Promise<void> {
    try {
      const builtIn = await import('./built-in-universes');
      for (const network of builtIn.default.networks || []) {
        await this.registerNetwork(network);
      }
      for (const entry of builtIn.default.universes) {
        for (const universe of Array.isArray(entry) ? entry : [entry]) {
          try {
            this.registerUniverse(universe['universeId'], universe as unknown as Universe);
          } catch (error) {
            console.warn(
              `Skipping invalid built-in universe: ${(universe as { universeId?: string })?.universeId}`,
              error,
            );
          }
        }
      }

    } catch (error) {
      console.warn('Failed to load built-in universes:', error);
    }
  }
  
  /**
   * Register the lore pipeline's generated universes when its (git-ignored) tree is
   * present — see {@link loadGeneratedUniverses}. They go through the same
   * `registerUniverse` path as everything else, so they are validated. A malformed
   * generated module is skipped with a warning rather than taking the registry down.
   */
  private async registerGeneratedUniverses(): Promise<void> {
    for (const universe of await loadGeneratedUniverses()) {
      try {
        this.registerUniverse(universe['universeId'] as string, universe);
      } catch (error) {
        console.warn(
          `Skipping invalid generated universe: ${(universe as { universeId?: string })?.universeId}`,
          error,
        );
      }
    }
  }

  private async loadExternalConfig(): Promise<void> {
    const configs = await this.configLoader.loadConfigurations();
    for (const config of configs) {
      for (const network of config.networks || []) {
        await this.registerNetwork(network);
      }
      for (const universe of config.universes) {
        this.registerUniverse(universe.universeId,universe);
      }

    }
  }
}
